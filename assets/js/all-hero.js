/*--- Shared Hero Content Helpers ---*/
function bpComHeroSetText(bpComHeroElement, bpComHeroText) {
    if (bpComHeroElement) {
        bpComHeroElement.textContent = bpComHeroText;
    }
}


/*--- Update Hero Button Text And Link ---*/
function bpComHeroSetLink(bpComHeroElement, bpComHeroText, bpComHeroHref) {
    if (!bpComHeroElement) {
        return;
    }

    bpComHeroElement.href = bpComHeroHref;

    Array.from(bpComHeroElement.childNodes).forEach(function (bpComHeroNode) {
        if (bpComHeroNode.nodeType === Node.TEXT_NODE) {
            bpComHeroNode.remove();
        }
    });

    const bpComHeroNestedIcon = bpComHeroElement.querySelector(".bp-com-hero-play-icon");

    if (bpComHeroNestedIcon) {
        bpComHeroElement.appendChild(document.createTextNode(" " + bpComHeroText));
        return;
    }

    const bpComHeroIcon = bpComHeroElement.querySelector(":scope > i");

    if (bpComHeroIcon) {
        bpComHeroElement.insertBefore(
            document.createTextNode(" " + bpComHeroText + " "),
            bpComHeroIcon
        );
    } else {
        bpComHeroElement.textContent = bpComHeroText;
    }
}


function bpComHeroSetSpanLabel(bpComHeroElement, bpComHeroText) {
    if (!bpComHeroElement) {
        return;
    }

    const bpComHeroIcon = bpComHeroElement.querySelector("i");

    if (bpComHeroIcon) {
        Array.from(bpComHeroElement.childNodes).forEach(function (bpComHeroNode) {
            if (bpComHeroNode.nodeType === Node.TEXT_NODE) {
                bpComHeroNode.remove();
            }
        });

        bpComHeroElement.insertBefore(
            document.createTextNode(" " + bpComHeroText + " "),
            bpComHeroIcon
        );
    } else {
        bpComHeroElement.textContent = bpComHeroText;
    }
}

/*--- Apply Page-Specific Hero Content ---*/
function bpComHeroApplyPageContent(bpComHero) {
    const bpComHeroPath = window.location.pathname.split("/").pop().toLowerCase();
    const bpComHeroPage = bpComHeroPages[bpComHeroPath];

    if (!bpComHeroPage) {
        return;
    }

    /*--- Breadcrumb And Main Content ---*/
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-breadcrumb [aria-current='page']"), bpComHeroPage.breadcrumb);
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-eyebrow span:nth-child(2)"), bpComHeroPage.eyebrow);

    const bpComHeroTitle = bpComHero.querySelector(".bp-com-hero-title");

    if (bpComHeroTitle) {
        const bpComHeroTitleHighlight = bpComHeroTitle.querySelector("span");

        if (bpComHeroTitleHighlight) {
            Array.from(bpComHeroTitle.childNodes).forEach(function (bpComHeroNode) {
                if (bpComHeroNode.nodeType === Node.TEXT_NODE) {
                    bpComHeroNode.remove();
                }
            });

            bpComHeroTitle.insertBefore(
                document.createTextNode(bpComHeroPage.titleStart + " "),
                bpComHeroTitleHighlight
            );

            bpComHeroTitleHighlight.textContent = bpComHeroPage.titleHighlight;
        } else {
            bpComHeroTitle.textContent = bpComHeroPage.titleStart + " " + bpComHeroPage.titleHighlight;
        }
    }

    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-description"), bpComHeroPage.description);

    bpComHeroSetLink(
        bpComHero.querySelector(".bp-com-hero-primary-btn"),
        bpComHeroPage.primaryText,
        bpComHeroPage.primaryLink
    );

    bpComHeroSetLink(
        bpComHero.querySelector(".bp-com-hero-secondary-btn"),
        bpComHeroPage.secondaryText,
        bpComHeroPage.secondaryLink
    );

    /*--- Highlight Items ---*/
    const bpComHeroHighlights = bpComHero.querySelectorAll(".bp-com-hero-highlight");

    if (bpComHeroHighlights[0]) {
        bpComHeroSetText(bpComHeroHighlights[0].querySelector("strong"), bpComHeroPage.highlightOneTitle);
        bpComHeroSetText(bpComHeroHighlights[0].querySelector("small"), bpComHeroPage.highlightOneText);
    }

    if (bpComHeroHighlights[1]) {
        bpComHeroSetText(bpComHeroHighlights[1].querySelector("strong"), bpComHeroPage.highlightTwoTitle);
        bpComHeroSetText(bpComHeroHighlights[1].querySelector("small"), bpComHeroPage.highlightTwoText);
    }

    /*--- Dashboard Heading ---*/
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-dashboard-welcome > span"), bpComHeroPage.workspaceLabel);
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-dashboard-welcome > strong"), bpComHeroPage.workspaceTitle);
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-dashboard-welcome > small"), bpComHeroPage.workspaceDescription);

    /*--- Dashboard Stat Cards ---*/
    const bpComHeroStats = bpComHero.querySelectorAll(".bp-com-hero-stat");

    if (bpComHeroStats[0]) {
        bpComHeroSetText(bpComHeroStats[0].querySelector("small"), bpComHeroPage.statOneLabel);
        bpComHeroSetText(bpComHeroStats[0].querySelector("strong"), bpComHeroPage.statOneTitle);
    }

    if (bpComHeroStats[1]) {
        bpComHeroSetText(bpComHeroStats[1].querySelector("small"), bpComHeroPage.statTwoLabel);
        bpComHeroSetText(bpComHeroStats[1].querySelector("strong"), bpComHeroPage.statTwoTitle);
    }

    /*--- Dashboard Workflow ---*/
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-workflow-heading strong"), bpComHeroPage.workflowTitle);
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-workflow-heading span"), bpComHeroPage.workflowTag);

    const bpComHeroWorkflowSteps = bpComHero.querySelectorAll(".bp-com-hero-workflow-step");

    const bpComHeroWorkflowContent = [
        { title: bpComHeroPage.stepOneTitle, text: bpComHeroPage.stepOneText },
        { title: bpComHeroPage.stepTwoTitle, text: bpComHeroPage.stepTwoText },
        { title: bpComHeroPage.stepThreeTitle, text: bpComHeroPage.stepThreeText }
    ];

    bpComHeroWorkflowSteps.forEach(function (bpComHeroStep, bpComHeroIndex) {
        const bpComHeroStepContent = bpComHeroWorkflowContent[bpComHeroIndex];

        if (!bpComHeroStepContent) {
            return;
        }

        bpComHeroSetText(bpComHeroStep.querySelector(".bp-com-hero-workflow-copy strong"), bpComHeroStepContent.title);
        bpComHeroSetText(bpComHeroStep.querySelector(".bp-com-hero-workflow-copy small"), bpComHeroStepContent.text);
    });

    /*--- Floating Information Cards ---*/
    const bpComHeroFloatSupplier = bpComHero.querySelector(".bp-com-hero-float-supplier");
    const bpComHeroFloatOrders = bpComHero.querySelector(".bp-com-hero-float-orders");

    if (bpComHeroFloatSupplier) {
        bpComHeroSetText(bpComHeroFloatSupplier.querySelector("strong"), bpComHeroPage.floatOneTitle);
        bpComHeroSetText(bpComHeroFloatSupplier.querySelector("small"), bpComHeroPage.floatOneText);
    }

    if (bpComHeroFloatOrders) {
        bpComHeroSetText(bpComHeroFloatOrders.querySelector("strong"), bpComHeroPage.floatTwoTitle);
        bpComHeroSetText(bpComHeroFloatOrders.querySelector("small"), bpComHeroPage.floatTwoText);
    }

    /*--- Visual Caption ---*/
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-visual-caption strong"), bpComHeroPage.captionTitle);
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-visual-caption small"), bpComHeroPage.captionText);

    /*--- Bottom Feature Strip ---*/
    bpComHeroSetText(bpComHero.querySelector(".bp-com-hero-bottom-label"), bpComHeroPage.bottomLabel);

    const bpComHeroBottomItems = bpComHero.querySelectorAll(".bp-com-hero-bottom-item");
    const bpComHeroBottomLabels = [
        bpComHeroPage.bottomOne,
        bpComHeroPage.bottomTwo,
        bpComHeroPage.bottomThree
    ];

    bpComHeroBottomItems.forEach(function (bpComHeroItem, bpComHeroIndex) {
        bpComHeroSetSpanLabel(bpComHeroItem, bpComHeroBottomLabels[bpComHeroIndex]);
    });

    bpComHero.dataset.heroContentApplied = "true";
}

/*--- Shared Hero Initialization ---*/
function bpComInitHero() {
    const bpComHeroSections = document.querySelectorAll("[data-bp-hero]");

    bpComHeroSections.forEach(function (bpComHero) {
        if (bpComHero.dataset.heroInitialized === "true") {
            return;
        }

        bpComHero.dataset.heroInitialized = "true";

        const bpComHeroVisual = bpComHero.querySelector("[data-bp-hero-visual]");
        const bpComHeroDashboard = bpComHero.querySelector(".bp-com-hero-dashboard");
        const bpComHeroDemoButton = bpComHero.querySelector("[data-bp-hero-demo]");
        const bpComHeroDashboardFooter = bpComHero.querySelector(".bp-com-hero-dashboard-footer span:nth-child(2)");
        const bpComHeroReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
        const bpComHeroFinePointer = window.matchMedia("(hover: hover) and (pointer: fine)");

        /*--- Load Page-Specific Content ---*/
        bpComHeroApplyPageContent(bpComHero);

        /*--- Interactive Dashboard Overview ---*/
        if (bpComHeroDemoButton && bpComHeroDashboardFooter) {
            bpComHeroDemoButton.addEventListener("click", function () {
                const bpComHeroIsExpanded = bpComHeroDemoButton.getAttribute("aria-expanded") === "true";

                bpComHeroDemoButton.setAttribute("aria-expanded", String(!bpComHeroIsExpanded));
                bpComHeroDemoButton.setAttribute(
                    "aria-label",
                    bpComHeroIsExpanded ? "Show workspace overview" : "Return to workspace overview"
                );

                bpComHeroDashboardFooter.textContent = bpComHeroIsExpanded
                    ? "Designed for connected procurement"
                    : "Workspace overview selected";

                bpComHeroDashboard.classList.toggle("bp-com-hero-dashboard-active", !bpComHeroIsExpanded);
            });
        }

        /*--- Desktop Pointer Interaction ---*/
        if (bpComHeroVisual && bpComHeroDashboard && bpComHeroFinePointer.matches && !bpComHeroReducedMotion.matches) {
            bpComHeroVisual.addEventListener("pointermove", function (bpComHeroEvent) {
                if (bpComHeroEvent.pointerType !== "mouse") {
                    return;
                }

                const bpComHeroBounds = bpComHeroVisual.getBoundingClientRect();
                const bpComHeroX = (bpComHeroEvent.clientX - bpComHeroBounds.left) / bpComHeroBounds.width;
                const bpComHeroY = (bpComHeroEvent.clientY - bpComHeroBounds.top) / bpComHeroBounds.height;
                const bpComHeroRotateY = (bpComHeroX - 0.5) * 7;
                const bpComHeroRotateX = (0.5 - bpComHeroY) * 5;

                bpComHeroDashboard.style.transform =
                    "rotateY(" + bpComHeroRotateY + "deg) rotateX(" + bpComHeroRotateX + "deg)";
            });

            bpComHeroVisual.addEventListener("pointerleave", function () {
                bpComHeroDashboard.style.transform = "";
            });
        }
    });
}

/*--- Initialize Hero On Page Load ---*/
if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", bpComInitHero);
} else {
    bpComInitHero();
}

/*--- Initialize Dynamically Added Hero Sections ---*/
document.addEventListener("bp:component-loaded", function () {
    bpComInitHero();
});
